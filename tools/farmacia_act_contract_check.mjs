function safeCreate(create, request) {
    try {
        return { result: create(request) };
    } catch (err) {
        return { threw: err };
    }
}

const sortedKeys = (obj) => Object.keys(obj).sort();

const describeValue = (v) => {
    if (typeof v === 'function') return 'function';
    if (typeof v === 'symbol') return 'symbol';
    try { return JSON.stringify(v) ?? String(v); } catch { return String(v); }
};

function isStructuredFailure(outcome) {
    if (outcome.threw) return false;
    const r = outcome.result;
    return !!r && typeof r === 'object'
        && r.ok === false
        && r.error && typeof r.error === 'object'
        && typeof r.error.code === 'string' && r.error.code.trim() !== ''
        && typeof r.error.message === 'string' && r.error.message !== ''
        && sortedKeys(r).join('|') === 'error|ok'
        // no fabricated act: no envelope field is exposed on a failure
        && BASE_ENVELOPE_KEYS.filter((k) => k !== 'ok').every((k) => r[k] === undefined)
        && r.amendment === undefined;
}

function isDeepCopiedFaithful(copy, original) {
    if (copy === original) return { pass: false, detail: 'same reference as input (not detached)' };
    if (typeof copy !== 'object' || copy === null || Array.isArray(copy)) return { pass: false, detail: 'copy is not an object' };
    if (sortedKeys(copy).join('|') !== sortedKeys(original).join('|')) return { pass: false, detail: `keys=${sortedKeys(copy).join('|')} expected=${sortedKeys(original).join('|')}` };
    if (JSON.stringify(copy) !== JSON.stringify(original)) return { pass: false, detail: 'not a faithful copy (JSON snapshot differs)' };
    return { pass: true, detail: '' };
}

function isOkActShape(result, request, expectAmendment) {
    if (!result || typeof result !== 'object' || result.ok !== true) return { pass: false, detail: 'result is not an ok result' };
    const expectedKeys = (expectAmendment ? WITH_AMENDMENT_KEYS : BASE_ENVELOPE_KEYS).join('|');
    if (sortedKeys(result).join('|') !== expectedKeys) return { pass: false, detail: `keys=${sortedKeys(result).join('|')} expected=${expectedKeys}` };
    if (result.contractVersion !== CONTRACT_VERSION) return { pass: false, detail: `contractVersion=${JSON.stringify(result.contractVersion)}` };
    const scalarFields = ['actId', 'revision', 'kind', 'siteId', 'patientRef', 'occurredAt', 'authoredAt', 'authorRef', 'attributionAssurance'];
    for (const f of scalarFields) {
        if (result[f] !== request[f]) return { pass: false, detail: `${f} not echoed verbatim` };
    }
    for (const f of ['payload', 'provenance']) {
        const check = isDeepCopiedFaithful(result[f], request[f]);
        if (!check.pass) return { pass: false, detail: `${f}: ${check.detail}` };
    }
    if (expectAmendment) {
        if (!request.amendment) return { pass: false, detail: 'oracle error: expectAmendment without input amendment' };
        const check = isDeepCopiedFaithful(result.amendment, request.amendment);
        if (!check.pass) return { pass: false, detail: `amendment: ${check.detail}` };
    }
    return { pass: true, detail: '' };
}

function attemptMutation(fn) {
    try {
        fn();
        return 'applied';
    } catch (err) {
        return `blocked (${err.constructor.name})`;
    }
}

