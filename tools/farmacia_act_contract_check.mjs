function familyA(create, degradedDetail) {
    console.log('  Family A — acceptance: valid creation for the 3 kinds, exact envelope, detachment, amendment, no autogen metadata');
    for (const kind of KINDS) {
        const name = `A valid ${kind} creates an ok Pharmacy Act v1 (exact envelope, verbatim echo, detached payload/provenance)`;
        if (!create) { record(name, false, degradedDetail); continue; }
        const request = { ...VALID_REQUEST(), kind };
        const outcome = safeCreate(create, request);
        if (outcome.threw) { record(name, false, `threw: ${outcome.threw.message}`); continue; }
        const shape = isOkActShape(outcome.result, request, false);
        record(name, shape.pass, shape.detail);
    }
    if (create) {
        // Valid amendment: echoed verbatim, detached, key present.
        const requestA = { ...VALID_REQUEST(), revision: 3, amendment: VALID_AMENDMENT(3) };
        const outcomeA = safeCreate(create, requestA);
        const shapeA = outcomeA.threw ? { pass: false, detail: `threw: ${outcomeA.threw.message}` } : isOkActShape(outcomeA.result, requestA, true);
        record('A valid amendment { previousRevision < revision, reason } is echoed verbatim and detached', shapeA.pass, shapeA.detail);

        // Absent amendment: NO 'amendment' key at all (no null placeholder).
        const outcomeB = safeCreate(create, VALID_REQUEST());
        record('A absent amendment produces an ok act with NO amendment key (no null/undefined placeholder)',
            !outcomeB.threw && outcomeB.result && outcomeB.result.ok === true && !('amendment' in outcomeB.result),
            outcomeB.threw ? `threw: ${outcomeB.threw.message}` : `hasKey=${outcomeB.result ? 'amendment' in outcomeB.result : 'n/a'}`);

        // Shared-but-acyclic reference inside payload is legal input.
        const shared = { dato: 'SYN' };
        const requestS = { ...VALID_REQUEST(), payload: { a: shared, b: shared } };
        const outcomeS = safeCreate(create, requestS);
        const shapeS = outcomeS.threw ? { pass: false, detail: `threw: ${outcomeS.threw.message}` } : isOkActShape(outcomeS.result, requestS, false);
        record('A shared-but-acyclic references inside payload are accepted (copied, not treated as cycles)', shapeS.pass, shapeS.detail);

        // No autogenerated metadata: identical explicit input -> deep-identical acts.
        const r1 = safeCreate(create, VALID_REQUEST());
        const r2 = safeCreate(create, VALID_REQUEST());
        record('A no autogen metadata: two creations from identical explicit input are deep-identical',
            !r1.threw && !r2.threw && JSON.stringify(r1.result) === JSON.stringify(r2.result),
            r1.threw || r2.threw ? 'threw' : 'results differ');

        // Falsification self-test: a planted wrong expectation must be
        // detected as FAIL by the checker itself (oracle can disagree).
        const outcome = safeCreate(create, VALID_REQUEST());
        const shape = outcome.threw ? { pass: false } : isOkActShape(outcome.result, VALID_REQUEST(), false);
        plantedSink.length = 0;
        plantedRecord('planted lie: contractVersion is pharmacy-act/v9', shape.pass && outcome.result.contractVersion === 'pharmacy-act/v9', 'actual contractVersion differs (expected for the planted lie)');
        record('A-f planted lie (wrong contractVersion) is detected as false',
            plantedDetectedAsFalse(), plantedSummary());
    } else {
        record('A valid amendment is echoed verbatim and detached', false, degradedDetail);
        record('A absent amendment produces an ok act with NO amendment key', false, degradedDetail);
        record('A shared-but-acyclic references inside payload are accepted', false, degradedDetail);
        record('A no autogen metadata: two creations from identical explicit input are deep-identical', false, degradedDetail);
        record('A-f planted lie (wrong contractVersion) is detected as false', false, degradedDetail);
    }
}

